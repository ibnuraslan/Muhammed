"""Romand film: the shot list as data. Each VO shot names the END of its VO segment (an ASCII snippet found after the
previous cut); the builder slices the segment out of romand/vo/ROMAND_Pn_VO.txt itself, so the narration is never
retyped and can never change. NV(...) shots carry no narration (title, disclaimer, holds) and give their own length.

Fields: set, kind, camera, action, overlay (kit template + params), sfx.
kind: CIN cinematic diorama | EXP top-down explainer (blue-grey slab, key object #E3FF00) | MAC extreme macro |
      MAP stylised map | 2D kit card over black / blurred plate.
Sets (reusable, see SETS in build_shotlist.py): FOR CAR PAR HPM HPI CLV UNI WHO CAF LIB HOT CRT PRI ABB CHU FTB HOS EXP MAP."""


def S(end, set_, kind, cam, act, ov="", sfx=""):
    return dict(end=end, set=set_, kind=kind, cam=cam, act=act, ov=ov, sfx=sfx)


def NV(dur, set_, kind, cam, act, ov="", sfx=""):
    return dict(end=None, dur=dur, set=set_, kind=kind, cam=cam, act=act, ov=ov, sfx=sfx)



"""Build romand/SHOTLIST.md (+ shots.json, shots.csv) from shots_data.py.
The VO segment of each shot is sliced out of romand/vo/ROMAND_Pn_VO.txt itself (never retyped), and the slices are
checked to rebuild the file exactly. Timing: 140 wpm, +0.25 s per sentence stop, +0.5 s after a paragraph break, NV shots use their own length.
    python3 build_shotlist.py"""
import os, re, json, csv
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
from shots_data import PARTS

WPM = 140.0
PARA_PAUSE = 0.5
SENT_PAUSE = 0.25   # natural pause after . ? ! ; :
SETS = {
    "FOR": "Forest road at night near Fontainebleau + the saloon car (exterior, boot, headlights)",
    "CAR": "Car interior (front seats, back seat, dome light, dash glow); same car asset as FOR",
    "PAR": "Paris: apartment block, wet street, cafe terrace, phone booth (night)",
    "HPM": "House in Prevessin-Moens: exterior (day, night, snow, fire, burnt) + garden swing + dollhouse cutaway",
    "HPI": "House interior: hallway, living room with TV + sofa, kitchen, staircase + landing, bedrooms",
    "CLV": "Parents' house in Clairvaux-les-Lacs (exterior + dining room); also used for family gatherings",
    "UNI": "Lyon medical faculty: exterior courtyard, exam hall, lecture hall, results board, registration desk, student room, archive",
    "WHO": "WHO headquarters Geneva: exterior slab + flags, public lobby with publications rack, empty office",
    "CAF": "Cafe interior / table",
    "LIB": "Library reading room (shelving reused as pharmacy)",
    "HOT": "Hotel near Geneva airport: exterior with runway + jet, room",
    "CRT": "Assize court Bourg-en-Bresse: exterior, courtroom, dock, gallery, witness stand",
    "PRI": "Prison: wall + gate, cell, prison library",
    "ABB": "Fontgombault abbey: exterior, cloister",
    "CHU": "Church steps (1980 wedding)",
    "FTB": "Phantom country house near Fontainebleau: lit windows, long empty dinner table",
    "HOS": "Small interiors: waiting room, sickroom, hospital room + corridor, ambulance",
    "EXP": "Explainer slab: top-down, dark blue-grey, pale pawns, key object #E3FF00",
    "MAP": "Kit map card (needs a France/Switzerland dataset)",
    "2D": "Kit card only (over black or the blurred previous plate)",
}


def words(t):
    return len(re.findall(r"[\w'’%-]+", t))


def build():
    out = {}
    for pn, P in PARTS.items():
        txt = open(os.path.join(ROOT, "vo", f"ROMAND_P{pn}_VO.txt"), encoding="utf-8").read()
        body = txt.strip()
        cur = 0; rows = []; t = 0.0; k = 0
        for sh in P["shots"]:
            k += 1
            sid = f"P{pn}-{k:02d}"
            if sh["end"] is None:
                seg = ""; dur = sh["dur"]; para = False
            else:
                j = body.find(sh["end"], cur)
                if j < 0:
                    raise SystemExit(f"{sid}: end snippet not found after cursor: {sh['end']!r}")
                e = j + len(sh["end"])
                raw = body[cur:e]; cur = e
                para = "\n" in body[cur:cur + 3] or cur >= len(body)
                seg = raw.strip()
                dur = words(seg) * 60.0 / WPM + (PARA_PAUSE if para else 0.0) + SENT_PAUSE * len(re.findall(r"[.?!;:](?=\s|$|[\u201d\"])", seg))
            rows.append(dict(id=sid, t0=round(t, 2), dur=round(dur, 2), vo=seg, words=words(seg), **{k_: sh[k_] for k_ in ("set", "kind", "cam", "act", "ov", "sfx")}))
            t += dur
        rest = body[cur:].strip()
        if rest:
            raise SystemExit(f"P{pn}: VO left uncovered: {rest[:80]!r}")
        # exact rebuild check: joining the slices (whitespace-normalised) gives the file back
        rebuilt = " ".join(r["vo"] for r in rows if r["vo"])
        if re.sub(r"\s+", " ", rebuilt) != re.sub(r"\s+", " ", body):
            raise SystemExit(f"P{pn}: rebuilt VO differs from file")
        out[pn] = dict(title=P["title"], rows=rows, total=round(t, 2), words=words(body), cold=P.get("cold_open_until"))
    return out


def fmt(s):
    return f"{int(s // 60)}:{s % 60:04.1f}"


def write(out):
    J = os.path.join(HERE, "shots.json"); json.dump(out, open(J, "w"), indent=1, ensure_ascii=False)
    with open(os.path.join(HERE, "shots.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f); w.writerow(["id", "start", "dur", "set", "kind", "camera", "action", "overlay", "sfx", "vo"])
        for pn, P in out.items():
            for r in P["rows"]:
                w.writerow([r["id"], fmt(r["t0"]), r["dur"], r["set"], r["kind"], r["cam"], r["act"], r["ov"], r["sfx"], r["vo"]])
    L = []
    tot = sum(P["total"] for P in out.values()); n = sum(len(P["rows"]) for P in out.values())
    L += ["# Romand film: shot list v1 (for hub review)", "",
          f"8 parts, **{n} shots**, about **{fmt(tot)}** at 140 wpm (estimated; retime to the recorded VO).",
          "Generated by `romand/shots/build_shotlist.py` from `shots_data.py`. Each shot's VO is sliced out of "
          "`romand/vo/ROMAND_Pn_VO.txt` and the slices are checked to rebuild every file exactly: **no word of the narration is changed**.", "",
          "## Rules applied", "",
          "- Look: STYLE_V2 (diorama in a black void, amber-gold world, faceless pale-clay mannequins in clothes, cool key + warm rim, one RED accent). "
          "Explainers (EXP) use the Engagement-rules slab: dark blue-grey, key object #E3FF00.",
          "- Pacing: cold open (P1-01 to P1-23) cuts every 1.5–4 s, hook ends on a hard stop at ~10 s (P1-04). "
          "Body shots average about 5–6 s (a little faster than the reference films' 7–8.5 s median), all with camera or subject motion.",
          "- Kinds alternate (CIN cinematic / EXP explainer / MAC macro / MAP / 2D card); no three of the same in a row where avoidable.",
          "- RED accent items only: nylon cord, tear-gas can, WHO badge (the one that never existed), rolling pin and rifle (silhouettes, never in use), petrol can, ankle tag.",
          "- Sensitivity: no violence on screen. The attack in the forest is seen from far above, withdrawing. The killings are implied by empty rooms, "
          "closed doors, the staircase and the house fire from outside. The children appear only from behind watching a cartoon and playing in the garden. "
          "No gunshot SFX: silence drops instead. Nothing beyond the script is shown as fact (Emmanuel's interpretation stays abstract).",
          "- Disclaimer: `disclaimer(discretion=True)` straight after the cold open and title (P1-24/25).",
          "- Person cards use our own faceless mannequin renders, never real photos (victims especially). Children get no portrait (a coat on a hook).",
          "- 0 clipping: every animated shot gets the per-frame clip check (bags, briefcases, doors, seats) before the final render.", "",
          "## Open questions for the hub", "",
          "1. Film title for the creepy title card (P1-24): placeholder only.",
          "2. Bernard Kouchner card (P6-02): mannequin portrait, text-only, or no card?",
          "3. Map card: the kit ships a Benelux dataset; I will add France/Switzerland outlines (Natural Earth, public domain) to the kit's map template.",
          "4. Document cards are illustrative recreations (French wording, no invented numbers or years). OK?",
          "5. Body pacing ~5–6 s: keep, or slow to the reference ~7–8 s?", "",
          "## Reusable sets", "", "| Code | Set |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in SETS.items()]
    L += ["", "## Summary per part", "", "| Part | Title | Shots | Words | Est. length |", "|---|---|---|---|---|"]
    for pn, P in out.items():
        L.append(f"| P{pn} | {P['title']} | {len(P['rows'])} | {P['words']} | {fmt(P['total'])} |")
    for pn, P in out.items():
        L += ["", f"## Part {pn}: {P['title']}  ({len(P['rows'])} shots, {fmt(P['total'])})", "",
              "| ID | Start | Dur | VO | Set / kind | Camera | Action | Overlay (kit) | SFX |", "|---|---|---|---|---|---|---|---|---|"]
        for r in P["rows"]:
            vo = r["vo"].replace("|", "/") if r["vo"] else "*(no VO)*"
            cell = lambda x: (x or "").replace("|", "/").replace("\n", " ")
            L.append(f"| {r['id']} | {fmt(r['t0'])} | {r['dur']:.1f} | {cell(vo)} | {r['set']} / {r['kind']} | {cell(r['cam'])} | "
                     f"{cell(r['act'])} | {('`' + cell(r['ov']) + '`') if r['ov'] else ''} | {cell(r['sfx'])} |")
    open(os.path.join(ROOT, "SHOTLIST.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"{n} shots, {fmt(tot)}")
    for pn, P in out.items():
        d = [r["dur"] for r in P["rows"] if r["vo"]]
        print(f"P{pn}: {len(P['rows'])} shots {fmt(P['total'])} mean {sum(d)/len(d):.1f}s max {max(d):.1f}s min {min(d):.1f}s")


if __name__ == "__main__":
    write(build())

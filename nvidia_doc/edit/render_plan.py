"""Work out every 3D render the edit needs, from the timeline.

  python edit/render_plan.py                  print the plan (jobs, frame counts, rough CPU time)
  python edit/render_plan.py --script         write out/render_all.sh (the full-quality render queue; not run)
  python edit/render_plan.py --preview        render quick low-res preview plates (storyboard only)
"""
import os, sys, json, math, importlib, subprocess
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
from beats import BEATS

ANIM_FPS = 12
SAMPLES = {"plate": 128, "anim": 64}
SEC_PER_FRAME = {"plate": 240, "anim": 75}       # rough 4-core CPU timings at 1920x1080, used for the estimate


def move_kinds():
    """Read MOVES from each scene module without importing bpy (parse kind= from the source)."""
    import re
    kinds = {}
    for f in os.listdir(os.path.join(ROOT, "scenes")):
        if f.startswith("sc_") and f.endswith(".py"):
            src = open(os.path.join(ROOT, "scenes", f)).read()
            scene = f[3:-3]
            for m in re.finditer(r'"(\w+)":\s*dict\(kind="(plate|anim)"', src):
                kinds[(scene, m.group(1))] = m.group(2)
            if "MOVES = {\"slow_push\": _d.MOVES" in src:
                kinds[(scene, "slow_push")] = "plate"
    return kinds


def plan():
    tl = json.load(open(os.path.join(HERE, "timeline.json")))
    span = {b["id"]: b["end"] - b["start"] for b in tl["beats"]}
    kinds = move_kinds()
    jobs = {}
    for b in BEATS:
        sh = b["shot"]
        scene = sh.get("scene") or sh.get("bg")
        if not scene:
            continue
        move = sh.get("move") if sh["kind"] != "mg" else None
        if move is None:            # graphics background plate: use the scene's first plate move
            move = next(m for (s_, m), k in kinds.items() if s_ == scene and k == "plate") if any(s_ == scene and k == "plate" for (s_, m), k in kinds.items()) else next(m for (s_, m) in kinds if s_ == scene)
        k = kinds.get((scene, move))
        if k is None:
            raise SystemExit(f"beat {b['id']}: scene {scene} has no move {move}")
        j = jobs.setdefault((scene, move), dict(kind=k, beats=[], seconds=0.0))
        j["beats"].append(b["id"]); j["seconds"] = max(j["seconds"], span.get(b["id"], 0))
    for (scene, move), j in jobs.items():
        j["frames"] = 1 if j["kind"] == "plate" else int(math.ceil(j["seconds"] * ANIM_FPS)) + 2
    return jobs


def main():
    jobs = plan()
    tot = 0
    print(f"{'scene':18} {'move':18} {'kind':6} {'frames':>6}  beats")
    for (scene, move), j in sorted(jobs.items()):
        cost = j["frames"] * SEC_PER_FRAME[j["kind"]] * (2 if j["kind"] == "plate" else 1)   # plates also render depth
        tot += cost
        print(f"{scene:18} {move:18} {j['kind']:6} {j['frames']:6d}  {', '.join(j['beats'])}")
    print(f"\n{len(jobs)} jobs · estimated {tot / 3600:.1f} CPU-hours at full quality on 4 cores")
    if "--script" in sys.argv:
        p = os.path.join(ROOT, "out", "render_all.sh"); os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write("#!/bin/bash\n# Full-quality 3D render queue for the edit (generated by edit/render_plan.py). Resumable.\n")
            f.write('PY=${PY:-python}\ncd "$(dirname "$0")/../scenes"\n')
            for (scene, move), j in sorted(jobs.items(), key=lambda kv: kv[1]["kind"]):
                if j["kind"] == "plate":
                    f.write(f"$PY run.py {scene} {move} --plate --samples {SAMPLES['plate']}\n")
                else:
                    f.write(f"$PY run.py {scene} {move} --anim {j['frames']} --samples {SAMPLES['anim']}\n")
        os.chmod(p, 0o755); print("wrote", p)
    if "--preview" in sys.argv:
        py = os.environ.get("PY", sys.executable)
        for (scene, move), j in sorted(jobs.items()):
            out = os.path.join(ROOT, "out", "plates_preview", scene, move)
            if os.path.exists(os.path.join(out, "plate.png")):
                continue
            subprocess.run([py, "run.py", scene, move, "--still", "--mid", "--lowres", "--samples", "12", "--out", out],
                           cwd=os.path.join(ROOT, "scenes"), stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            print("[preview]", scene, move, flush=True)


if __name__ == "__main__":
    main()
